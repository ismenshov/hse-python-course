# Задача 2.1. Площадь круга
# ============================================================
# Запросите радиус (вещественное число).
# Выведите площадь круга и длину окружности с точностью
# до двух знаков.
#
# Пример:
#   In: 3.0
#   Out: S = 28.27, C = 18.85
#
# Подсказка: используйте math.pi и f-строки.


def task_2_1(radius: float) -> tuple:
    print(f"S = {(math.pi * radius ** 2):.2f}, C = {(2 * math.pi * radius):.2f}")


